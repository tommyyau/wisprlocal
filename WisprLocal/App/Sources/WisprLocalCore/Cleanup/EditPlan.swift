import Foundation

public enum EditDisposition: String, Sendable { case keep, filler, falseStart, retracted }
public enum PlanPunctuation: String, Sendable {
    case none, comma, period, question, exclamation, colon, semicolon
    var text: String { switch self { case .none: ""; case .comma: ","; case .period: "."; case .question: "?"; case .exclamation: "!"; case .colon: ":"; case .semicolon: ";" } }
}
public enum PlanBreak: String, Sendable { case none, newline, paragraph, listItem }
public enum PlanArticle: String, Sendable { case a, an, the }

public struct EditSpan: Sendable {
    public var start: Int
    public var end: Int
    public var disposition: EditDisposition
    public var correctionCueIndex: Int?
    public init(start: Int, end: Int, disposition: EditDisposition, correctionCueIndex: Int? = nil) {
        self.start = start; self.end = end; self.disposition = disposition; self.correctionCueIndex = correctionCueIndex
    }
}
public struct EditBoundary: Sendable {
    public var afterToken: Int
    public var punctuation: PlanPunctuation
    public var lineBreak: PlanBreak
    public init(afterToken: Int, punctuation: PlanPunctuation = .none, lineBreak: PlanBreak = .none) {
        self.afterToken = afterToken; self.punctuation = punctuation; self.lineBreak = lineBreak
    }
}
public struct ArticleInsertion: Sendable {
    public var beforeToken: Int
    public var article: PlanArticle
    public init(beforeToken: Int, article: PlanArticle) { self.beforeToken = beforeToken; self.article = article }
}
public struct EditPlan: Sendable {
    public var spans: [EditSpan]
    public var boundaries: [EditBoundary]
    public var articles: [ArticleInsertion]
    public var leadingList: Bool
    public init(spans: [EditSpan], boundaries: [EditBoundary] = [], articles: [ArticleInsertion] = [], leadingList: Bool = false) {
        self.spans = spans; self.boundaries = boundaries; self.articles = articles; self.leadingList = leadingList
    }
}

/// Indexed original surfaces; symbols and numeric identity are never regenerated by a model.
public struct PlanTokens: Sendable {
    public let surfaces: [String]
    let keys: [String]
    let gaps: [String]
    let prefix: String
    let quotedIndices: Set<Int>
    public init(_ text: String) {
        let ns = text as NSString
        let matches = Tokenizer.tokenRegex.matches(in: text, range: NSRange(location: 0, length: ns.length))
        surfaces = matches.map { ns.substring(with: $0.range) }
        keys = surfaces.map { $0.lowercased().replacingOccurrences(of: "’", with: "'").replacingOccurrences(of: "ʼ", with: "'").replacingOccurrences(of: "‘", with: "'") }
        prefix = matches.first.map { ns.substring(to: $0.range.location) } ?? text
        gaps = matches.enumerated().map { i, m in
            let end = NSMaxRange(m.range), next = i + 1 < matches.count ? matches[i + 1].range.location : ns.length
            return ns.substring(with: NSRange(location: end, length: next - end))
        }
        var quoted = false, indices = Set<Int>()
        func scanQuotes(_ gap: String) {
            for ch in gap where "\"“”‘’'".contains(ch) { quoted.toggle() }
        }
        scanQuotes(prefix)
        for index in keys.indices {
            if quoted { indices.insert(index) }
            scanQuotes(gaps[index])
        }
        quotedIndices = indices
    }
}
/// Per-span deletion checks shared by every projection candidate.
public enum PlanValidator {
    static let imperativeVerbs: Set<String> = ["send", "use", "meet", "put", "place", "call", "email", "book", "invite", "fly", "pay", "bring", "keep", "stop", "don't"]
    static let fillers: [[String]] = ["um", "uh", "erm", "hmm", "like", "you know", "i mean", "kind of", "sort of", "basically", "actually", "so", "well", "right", "okay"].map { $0.split(separator: " ").map(String.init) }
    static let cues: [[String]] = ["sorry i meant", "no wait", "wait no", "i mean", "i meant", "sorry", "actually", "or rather", "make that", "scratch that", "never mind"].map { $0.split(separator: " ").map(String.init) }
    static let cuesByHead = Dictionary(grouping: cues, by: { $0[0] })
    static let meaning: Set<String> = ["must", "may", "might", "can", "could", "will", "would", "shall", "should", "only", "all", "every", "except", "unless", "maybe", "probably", "never", "always"]
    static let directions = Set(["before", "after", "with", "without", "above", "below", "in", "out", "on", "off", "up", "down", "left", "right"]).union(["to", "at", "from", "into", "onto", "through", "toward", "between"])
    static let singleFillers = Set(fillers.filter { $0.count == 1 }.map { $0[0] })
    static let function = StutterRemover.functionWords.union(directions).union(["the", "a", "an", "it", "please", "instead", "is", "was", "are", "were"])
    static func fillerOnly(_ words: ArraySlice<String>) -> Bool {
        var i = words.startIndex
        while i < words.endIndex {
            guard let phrase = fillers.first(where: { i + $0.count <= words.endIndex && words[i..<(i + $0.count)].elementsEqual($0) }) else { return false }
            i += phrase.count
        }
        return true
    }
    static let weekdays = Backtrack.weekdays
    static let times: Set<String> = ["today", "tomorrow", "tonight", "yesterday", "morning", "afternoon", "evening", "noon", "midnight", "am", "pm", "o'clock"]
    static let months = Set(Backtrack.months.map { $0.lowercased() })
    static func sameSlot(_ a: String, _ b: String) -> Bool {
        return (times.contains(a) && times.contains(b)) || (a.contains(where: \.isNumber) && b.contains(where: \.isNumber)) || (Backtrack.numberWords.contains(a) && Backtrack.numberWords.contains(b)) || (weekdays.contains(a) && weekdays.contains(b)) || (months.contains(a) && months.contains(b))
    }
    static func protected(_ tokens: PlanTokens, index: Int, terms: Set<String>) -> Bool {
        let word = tokens.keys[index]
        return word.contains(where: \.isNumber) || Backtrack.numberWords.contains(word) || Tokenizer.isNegator(word) || meaning.contains(word) || weekdays.contains(word) || months.contains(word) || times.contains(word) || directions.contains(word) || terms.contains(word) || !word.contains(where: \.isLetter)
    }

    static func removableFiller(_ tokens: PlanTokens, range: Range<Int>, terms: Set<String>) -> Bool {
        FillerContext.allRemovable(tokens, range: range) && !range.contains { protected(tokens, index: $0, terms: terms) && tokens.keys[$0] != "right" }
    }

    static func incompletePlacement(_ tokens: PlanTokens, range: Range<Int>) -> Bool {
        let words = tokens.keys, end = range.upperBound
        return range.count == 4 && end + 4 < words.count &&
            ["put", "place", "leave", "set", "keep"].contains(words[range.lowerBound]) &&
            ["it", "them", "this", "that"].contains(words[range.lowerBound + 1]) &&
            ["the", "a", "an"].contains(words[end - 1]) && directions.contains(words[end - 2]) &&
            words[range.lowerBound..<range.lowerBound + 2].elementsEqual(words[end..<end + 2]) &&
            directions.contains(words[end + 2]) && ["the", "a", "an"].contains(words[end + 3])
    }

    static func falseStartReason(_ tokens: PlanTokens, range: Range<Int>, isClauseStart: Bool,
                                 restartEnd: Int, terms: Set<String>) -> String? {
        let words = tokens.keys, n = words.count
        guard range.upperBound < n, range.count <= 5, isClauseStart,
              !range.contains(where: { tokens.gaps[$0].contains(where: { ".!?;\n".contains($0) }) || $0 < range.upperBound - 1 && tokens.gaps[$0].contains(",") }) else { return "false-start-clause" }
        let restart = range.upperBound..<restartEnd
        let two = range.count >= 2 && restart.count >= 2 && words[range.lowerBound..<range.lowerBound + 2].elementsEqual(words[range.upperBound..<range.upperBound + 2])
        let head = range.first { !function.contains(words[$0]) && !singleFillers.contains(words[$0]) }
        guard two || head.map({ words[$0] == words[range.upperBound] }) == true else { return "false-start-restart" }
        let incompletePlace = incompletePlacement(tokens, range: range)
        guard !tokens.gaps[range.upperBound - 1].contains(",") || function.contains(words[range.upperBound - 1]) else { return "false-start-complete" }
        // A restart cannot silently discard names, terms or content nouns.
        // Every content token, including the lexical head, must be restated.
        for i in range where !function.contains(words[i]) && !singleFillers.contains(words[i]) {
            guard restart.contains(where: { words[$0] == words[i] }) else { return "false-start-content" }
        }
        for i in range where protected(tokens, index: i, terms: terms) {
            guard restart.contains(where: { words[$0] == words[i] || incompletePlace && directions.contains(words[i]) && !terms.contains(words[i]) && directions.contains(words[$0]) }) else { return "false-start-protected" }
        }
        return nil
    }

    static func retractionReason(_ tokens: PlanTokens, range: Range<Int>, cueEnd post: Int,
                                 postEnd: Int, clauseStarts: Set<Int>, terms: Set<String>) -> String? {
        let words = tokens.keys
        guard post < words.count, post < postEnd else { return "retraction-restatement" }
        let following = words[post..<postEnd]
        func protected(_ i: Int) -> Bool { Self.protected(tokens, index: i, terms: terms) }
        func isName(_ i: Int) -> Bool {
            terms.contains(words[i]) || (tokens.surfaces[i].first?.isUppercase == true &&
                !function.contains(words[i]) && !singleFillers.contains(words[i]) && !imperativeVerbs.contains(words[i]))
        }
        func rigidMeaning(_ i: Int) -> Bool {
            Tokenizer.isNegator(words[i]) || (meaning.contains(words[i]) && !(months.contains(words[i]) && tokens.surfaces[i].first?.isUppercase == true))
        }
        func counterpart(_ i: Int, _ j: Int) -> Bool {
            if rigidMeaning(i) { return words[i] == words[j] }
            return words[i] == words[j] || sameSlot(words[i], words[j]) || (isName(i) && isName(j)) || (directions.contains(words[i]) && directions.contains(words[j]))
        }
        // Negation and modality must themselves be restated, even if the verb repeats.
        for i in range where rigidMeaning(i) {
            guard following.contains(words[i]) else { return "retraction-meaning" }
        }
        // A short Backtrack-style slot can follow kept clause scaffolding (Meet at 3).
        // It may never contain a predicate or cross a clause boundary.
        let slotOnly = range.count <= 3 && range.allSatisfy { function.contains(words[$0]) || protected($0) || isName($0) } &&
            (directions.contains(words[range.lowerBound]) || protected(range.lowerBound) || isName(range.lowerBound))
        guard clauseStarts.contains(range.lowerBound) || slotOnly,
              !range.contains(where: { tokens.gaps[$0].contains(where: { ".!?;\n".contains($0) }) || $0 < range.upperBound - 1 && tokens.gaps[$0].contains(",") }) else { return "retraction-clause" }
        let head = range.first { !function.contains(words[$0]) && !singleFillers.contains(words[$0]) }
        let postHead = (post..<postEnd).first { !function.contains(words[$0]) && !singleFillers.contains(words[$0]) }
        let place = directions.contains(words[range.lowerBound]) && directions.contains(words[post])
        guard place || (head != nil && postHead != nil && counterpart(head!, postHead!)) else { return "retraction-restatement" }
        // Locate the subject itself, not the first content head (which may
        // already be the verb for pronoun-led clauses).
        func predicate(_ range: Range<Int>) -> Int? {
            let subject = range.first { !singleFillers.contains(words[$0]) }
            guard let subject else { return nil }
            if ["i", "we", "you", "he", "she", "they", "it", "i'm", "it's"].contains(words[subject]) { return subject + 1 }
            if ["the", "a", "an"].contains(words[subject]) { return subject + 2 }
            if subject + 1 < range.upperBound && !directions.contains(words[subject]) && !imperativeVerbs.contains(words[subject]) && !sameSlot(words[subject], words[subject]) { return subject + 1 }
            return nil
        }
        if let verb = predicate(range) {
            guard let postVerb = predicate(post..<postEnd), verb < range.upperBound,
                  postVerb < postEnd, words[verb] == words[postVerb] else { return "retraction-predicate" }
        }
        var available = Set(post..<postEnd)
        for i in range where protected(i) || isName(i) {
            guard let j = available.sorted().first(where: { counterpart(i, $0) }) else { return "retraction-protected" }
            available.remove(j)
        }
        return nil
    }

}

/// Renders only app-owned, validated projection decisions.
enum ProjectionRenderer {
    static func render(_ tokens: PlanTokens, removed: [Bool], boundaries: [Int: EditBoundary],
                               articles: [Int: String], dictionary: [String], contextNames: [String], leadingList: Bool = false) -> String {
        let words = tokens.keys, n = words.count
        // Dictionary spellings alone may restore canonical casing. Context hints only
        // freeze the exact surfaces already present; IT/US/Grace never recase common words.
        var renderSurfaces = tokens.surfaces
        let dictionaryTokens = dictionary.map(PlanTokens.init).filter { !$0.surfaces.isEmpty }
        let dictionaryByHead = Dictionary(grouping: dictionaryTokens, by: { $0.keys[0] })
        for i in words.indices where !removed[i] {
            for term in dictionaryByHead[words[i]] ?? [] {
                let end = i + term.keys.count
                if end <= n, words[i..<end].elementsEqual(term.keys), !(i..<end).contains(where: { removed[$0] }) {
                    for j in term.keys.indices { renderSurfaces[i + j] = term.surfaces[j] }
                }
            }
        }
        let exactNames = Set(contextNames.flatMap { PlanTokens($0).surfaces } + dictionaryTokens.flatMap(\.surfaces))
        var gaps = tokens.gaps, prefix = tokens.prefix
        // Drop paired brackets whose complete contents were removed, including the opener
        // attached to the previous kept token's gap.
        var stack: [(Character, Int)] = []
        let pairs: [Character: Character] = ["(": ")", "[": "]", "{": "}"]
        for position in -1..<n {
            let gap = position < 0 ? prefix : gaps[position]
            for ch in gap {
                if pairs[ch] != nil { stack.append((ch, position)) }
                else if let open = stack.last, pairs[open.0] == ch {
                    stack.removeLast()
                    if (open.1 + 1...max(open.1 + 1, position)).allSatisfy({ $0 < n && removed[$0] }) {
                        if open.1 < 0 { prefix.removeAll { $0 == open.0 } }
                        else { gaps[open.1].removeAll { $0 == open.0 } }
                        gaps[position].removeAll { $0 == ch }
                    }
                }
            }
        }
        var previousKept: Int?
        for i in words.indices {
            if !removed[i] { previousKept = i; continue }
            guard let previousKept else { continue }
            let punctuation = gaps[i].filter { ".!?;\n)]}”’\"".contains($0) }
            if !punctuation.isEmpty {
                gaps[previousKept] = gaps[previousKept].trimmingCharacters(in: .whitespacesAndNewlines)
                if punctuation.contains(where: { ".!?".contains($0) }) { gaps[previousKept].removeAll { $0 == "," } }
                gaps[previousKept] += punctuation + " "
            }
        }
        var output = (leadingList ? "- " : "") + prefix, sentenceStart = true
        for i in words.indices where !removed[i] {
            var surface = renderSurfaces[i]
            if let article = articles[i] {
                output += sentenceStart ? article.capitalized + " " : article + " "
                sentenceStart = false
            }
            if sentenceStart && !exactNames.contains(surface) { surface = surface.prefix(1).uppercased() + surface.dropFirst() }
            output += surface
            sentenceStart = false
            if let b = boundaries[i] {
                let originalGap = gaps[i].trimmingCharacters(in: .whitespacesAndNewlines)
                output += originalGap.contains(where: { ".?!".contains($0) }) ? originalGap : b.punctuation.text
                switch b.lineBreak {
                case .none: output += " "
                case .newline: output += "\n"
                case .paragraph: output += "\n\n"
                case .listItem: output += "\n- "
                }
                sentenceStart = [.period, .question, .exclamation].contains(b.punctuation) || b.lineBreak != .none
            } else {
                let gap = gaps[i]
                output += gap
                sentenceStart = gap.contains(where: { ".!?\n".contains($0) })
            }
        }
        return output.trimmingCharacters(in: .whitespacesAndNewlines)
    }
}
